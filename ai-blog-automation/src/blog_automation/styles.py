"""Per-blog writing-style presets.

Before this module the drafting phase used ONE hardcoded
``ARTICLE_SYSTEM_PROMPT``, so every blog generated by this pipeline sounded
identical no matter the brand. The writing voice is now a first-class,
per-blog knob.

Resolution order (first hit wins):

1. explicit ``style`` argument (e.g. ``scripts/run.py "kw" --style story``)
2. env ``ARTICLE_STYLE``      — one-run override
3. env ``BLOG_STYLE_FILE``    — path to a markdown/text file holding the FULL
                                custom system prompt (per-blog voice, any size)
4. env ``BLOG_STYLE``         — preset name (per-blog default; .env or
                                Streamlit secrets)
5. ``DEFAULT_STYLE``          — ``warm-editorial``, byte-identical to the old
                                prompt, so unset env = previous behaviour

``custom:<text>`` is accepted anywhere a style name goes — the text after the
colon is used verbatim as the system prompt.

Example (.env of a new blog)::

    BLOG_STYLE=punchy-listicle
    # or fully bespoke:
    BLOG_STYLE_FILE=./styles/forgeblast.md
"""

from __future__ import annotations

import os
from dataclasses import dataclass

# The original drafting system prompt. Kept as the `warm-editorial` preset and
# as the fallback so nothing changes for sites that don't set a style.
DEFAULT_SYSTEM_PROMPT = """\
You are a professional blog writer creating engaging, well-researched content.

Guidelines:
- Conversational tone, avoid robotic language
- Short paragraphs (2-3 sentences max)
- Include real-world examples and use cases
- Natural keyword integration (3-5 times total)
- No keyword stuffing
- Cite sources where appropriate using [Source: URL] format
- Internal link anchors: [anchor text](article-slug)
- Use bullet points and numbered lists where appropriate
- Include actionable takeaways
- Write for humans first, SEO second"""


@dataclass(frozen=True)
class Style:
    """A resolved writing style."""

    name: str
    label: str
    system_prompt: str
    outline_hint: str = ""
    temperature: float = 0.7

    @property
    def slug(self) -> str:
        return self.name


# ---------------------------------------------------------------------------
