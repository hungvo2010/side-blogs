DEFAULT_STYLE = "warm-editorial"


def list_styles() -> list[str]:
    """Return the available preset names."""
    return list(STYLE_PRESETS)


def _from_file(path: str) -> Style | None:
    try:
        with open(path, encoding="utf-8") as fh:
            text = fh.read().strip()
    except OSError:
        return None
    if not text:
        return None
    # A leading "label: ..." line is optional; everything else is the prompt.
    label = os.path.splitext(os.path.basename(path))[0]
    lines = text.splitlines()
    if lines and lines[0].lower().startswith("label:"):
        label = lines[0].split(":", 1)[1].strip() or label
        text = "\n".join(lines[1:]).strip()
    return Style(name=f"file:{path}", label=label, system_prompt=text)


def resolve_style(
    style: str | None = None,
    *,
    env_style: str | None = None,
    env_style_file: str | None = None,
) -> Style:
    """Resolve the style to use. See module docstring for the precedence order."""

    def _from_name(name: str) -> Style | None:
        name = (name or "").strip()
        if not name:
            return None
        if name.startswith("custom:"):
            text = name.split(":", 1)[1].strip()
            if text:
                return Style(
                    name="custom", label="Custom (inline)", system_prompt=text
                )
            return None
        if name in STYLE_PRESETS:
            preset = STYLE_PRESETS[name]
            return Style(
                name=name,
                label=preset["label"],
                system_prompt=preset["system_prompt"],
                outline_hint=preset.get("outline_hint", ""),
                temperature=preset.get("temperature", 0.7),
            )
        # Unknown name -> treat as a raw prompt rather than silently ignoring it.
        return Style(name=name, label=f"Custom ({name[:24]})", system_prompt=name)

    for candidate in (
        style,
        env_style if env_style is not None else os.environ.get("ARTICLE_STYLE"),
    ):
        resolved = _from_name(candidate or "")
        if resolved:
            return resolved

    file_path = (
        env_style_file
        if env_style_file is not None
        else os.environ.get("BLOG_STYLE_FILE")
    )
    if file_path:
        resolved = _from_file(os.path.expanduser(file_path))
        if resolved:
            return resolved

    resolved = _from_name(os.environ.get("BLOG_STYLE", "") or DEFAULT_STYLE)
    if resolved:
        return resolved
    default = STYLE_PRESETS[DEFAULT_STYLE]
    return Style(
        name=DEFAULT_STYLE,
        label=default["label"],
        system_prompt=DEFAULT_SYSTEM_PROMPT,
        outline_hint=default["outline_hint"],
    )


def build_system_prompt(
    style: str | None = None,
    *,
    site_name: str | None = None,
    author: str | None = None,
    extra: str = "",
) -> str:
    """Build the drafting system prompt for the active (or named) style."""
    resolved = resolve_style(style)
    parts = [resolved.system_prompt.rstrip()]
    site = site_name or os.environ.get("SITE_NAME")
    if site:
        parts.append(
            f"Publication: {site}."
            + (f" Author byline: {author}." if author else "")
            + " Keep the voice consistent with this publication's brand."
        )
    if extra.strip():
        parts.append(extra.strip())
    return "\n\n".join(parts)


def outline_hint(style: str | None = None) -> str:
    """The outline-level nudge for the active style (may be empty)."""
    return resolve_style(style).outline_hint


def active_temperature(style: str | None = None, default: float = 0.7) -> float:
    """Sampling temperature for the active style."""
    return resolve_style(style).temperature or default


def describe() -> str:
    """One-line summary of the active style, for run logs."""
    resolved = resolve_style()
    return f"{resolved.name} ({resolved.label}), temp={resolved.temperature}"
